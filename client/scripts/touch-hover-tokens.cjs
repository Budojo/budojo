#!/usr/bin/env node
/**
 * Writes `src/styles/_touch-hover-tokens.scss` (#2034): on a touch screen,
 * every PrimeNG hover token takes its resting value, so a tapped button or
 * row does not keep its hover colour after the finger has gone.
 *
 * PrimeNG injects its styles at runtime, so they never pass through the
 * build's PostCSS (`scripts/postcss-hover-gate.cjs` gates our own). What it
 * does read is its design tokens, as CSS variables: under `(hover: none)`,
 * `--p-button-primary-hover-background` becomes
 * `var(--p-button-primary-background)`, and a hover background with no
 * resting token (a text button's) becomes `transparent`, which is what that
 * button paints at rest.
 *
 *   node scripts/touch-hover-tokens.cjs          # write the partial
 *   (touch-hover-tokens.spec.ts fails when it is stale)
 */
const { writeFileSync } = require('node:fs');
const { join } = require('node:path');

const OUT = join(__dirname, '..', 'src', 'styles', '_touch-hover-tokens.scss');
const SKIP = new Set(['colorScheme', 'light', 'dark', 'root']);

const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const variable = (path) =>
  `--p-${path
    .filter((p) => !SKIP.has(p))
    .map(kebab)
    .join('-')}`;

/** Every string token of the preset's components, by CSS variable name. */
function tokens(components) {
  const found = new Map();
  const walk = (node, path) => {
    for (const [key, value] of Object.entries(node ?? {})) {
      if (key === 'css') continue;
      if (value && typeof value === 'object') walk(value, [...path, key]);
      else if (typeof value === 'string') found.set(variable([...path, key]), [...path, key]);
    }
  };
  walk(components, []);
  return found;
}

/** `[hover variable, resting value]` pairs, sorted. */
function pairs(components) {
  const all = tokens(components);
  const out = new Map();
  for (const [name, path] of all) {
    const key = path[path.length - 1];
    if (!/^(active)?[hH]over/.test(key)) continue;
    const restingKey = key
      .replace(/^(active)?[hH]over/, '$1')
      .replace(/^./, (c) => c.toLowerCase());
    const resting = variable([...path.slice(0, -1), restingKey]);
    if (all.has(resting)) out.set(name, `var(${resting})`);
    else if (/background$/i.test(key)) out.set(name, 'transparent');
  }
  return [...out.entries()].sort(([a], [b]) => a.localeCompare(b));
}

/** The partial, formatted as Prettier formats the rest of `src/` (it runs over it). */
async function render(components) {
  const prettier = require('prettier');
  const lines = pairs(components).map(([name, value]) => `    ${name}: ${value};`);
  const css = [
    '// Generated by `node scripts/touch-hover-tokens.cjs` — do not edit (#2034).',
    '// On a touch screen a tap leaves the pointer where it was, so hover sticks:',
    "// PrimeNG's hover tokens take their resting value there.",
    '@media (hover: none) {',
    '  :root {',
    ...lines,
    '  }',
    '}',
    '',
  ].join('\n');
  const options = await prettier.resolveConfig(OUT);
  return prettier.format(css, { ...options, filepath: OUT });
}

/** Every CSS variable the preset's components define, for the ghost-token guard. */
function variables(components) {
  return [...tokens(components).keys()];
}

module.exports = { render, pairs, variables };

if (require.main === module) {
  const preset = require('@primeuix/themes/material').default;
  render(preset.components).then((css) => {
    writeFileSync(OUT, css);
    console.log(`wrote ${OUT}: ${pairs(preset.components).length} tokens`);
  });
}
